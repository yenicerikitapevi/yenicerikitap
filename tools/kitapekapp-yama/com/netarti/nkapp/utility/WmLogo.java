    private static synchronized float[][] mask() {
        if (mask == null) {
            byte[] b = Base64.getDecoder().decode(String.join("", B64));
            float[][] m = new float[MH][MW];
            for (int y = 0; y < MH; y++) for (int x = 0; x < MW; x++) m[y][x] = (b[y * MW + x] & 255) / 255f;
            mask = m;
        }
        return mask;
    }

    /** Şablonu k katına ölçekler (çift doğrusal) */
    static float[][] scaled(double k) {
        float[][] m = mask();
        if (Math.abs(k - 1) < 0.01) return m;
        int w = Math.max(1, (int) Math.round(MW * k)), h = Math.max(1, (int) Math.round(MH * k));
        float[][] o = new float[h][w];
        for (int y = 0; y < h; y++) {
            double sy = Math.min(MH - 1.001, Math.max(0, (y + 0.5) / k - 0.5)); int y0 = (int) sy; double fy = sy - y0;
            for (int x = 0; x < w; x++) {
                double sx = Math.min(MW - 1.001, Math.max(0, (x + 0.5) / k - 0.5)); int x0 = (int) sx; double fx = sx - x0;
                o[y][x] = (float) ((m[y0][x0] * (1 - fx) + m[y0][x0 + 1] * fx) * (1 - fy) + (m[y0 + 1][x0] * (1 - fx) + m[y0 + 1][x0 + 1] * fx) * fy);
            }
        }
        return o;
    }

    static float[][] highPass(float[][] a, int r) {
        int h = a.length, w = a[0].length;
        double[][] I = new double[h + 1][w + 1];
        for (int y = 0; y < h; y++) for (int x = 0; x < w; x++) I[y + 1][x + 1] = a[y][x] + I[y][x + 1] + I[y + 1][x] - I[y][x];
        float[][] o = new float[h][w];
        for (int y = 0; y < h; y++) for (int x = 0; x < w; x++) {
            int y0 = Math.max(0, y - r), y1 = Math.min(h, y + r + 1), x0 = Math.max(0, x - r), x1 = Math.min(w, x + r + 1);
            o[y][x] = (float) (a[y][x] - (I[y1][x1] - I[y0][x1] - I[y1][x0] + I[y0][x0]) / ((y1 - y0) * (x1 - x0)));
        }
        return o;
    }

    /** Son aramanın benzerlik puanı (test/günlük için) */
    public static volatile double lastScore = 0;

    public static BufferedImage clean(BufferedImage img) {
        try {
            int w = img.getWidth(), h = img.getHeight();
            double k = w / (double) REF_W;
            lastScore = 0;
            if (k < 0.6 || k > 4 || h < 100 * k) return img;
            float[][] a = scaled(k);
            int mh = a.length, mw = a[0].length;
            int bx = (int) Math.round(OFF_X * k), by = h - (int) Math.round(OFF_BOTTOM * k);
            int R = Math.max(3, (int) Math.round(3 * k)), hr = Math.max(3, (int) Math.round(7 * k));
            // Arama bölgesi (şablon + kayma payı) parlaklığı
            int rx0 = bx - R, ry0 = by - R, rw = mw + 2 * R, rh = mh + 2 * R;
            if (rx0 < 0 || ry0 < 0 || rx0 + rw > w || ry0 + rh > h) return img;
            float[][] lum = new float[rh][rw];
            for (int y = 0; y < rh; y++) for (int x = 0; x < rw; x++) {
                int c = img.getRGB(rx0 + x, ry0 + y);
                lum[y][x] = 0.299f * ((c >> 16) & 255) + 0.587f * ((c >> 8) & 255) + 0.114f * (c & 255);
            }
            float[][] lh = highPass(lum, hr), ah = highPass(a, hr);
            double aa = 0;
            for (float[] row : ah) for (float v : row) aa += v * v;
            double best = -2; int bdx = 0, bdy = 0;
            for (int dy = 0; dy <= 2 * R; dy++) for (int dx = 0; dx <= 2 * R; dx++) {
                double s = 0, ll = 0;
                for (int y = 0; y < mh; y++) for (int x = 0; x < mw; x++) { float v = lh[y + dy][x + dx]; s += v * ah[y][x]; ll += v * v; }
                double ncc = s / Math.sqrt(ll * aa + 1e-9);
                if (ncc > best) { best = ncc; bdx = dx; bdy = dy; }
            }
            lastScore = best;
            if (best < MIN_SCORE) return img;
            int x0 = rx0 + bdx, y0 = ry0 + bdy;

            // Logo pikselleri ve çevresi
            boolean[][] soft = new boolean[mh][mw], big = new boolean[mh][mw];
            for (int y = 0; y < mh; y++) for (int x = 0; x < mw; x++) soft[y][x] = a[y][x] > 0.004f;
            for (int y = 0; y < mh; y++) for (int x = 0; x < mw; x++) {
                boolean b = false;
                for (int j = -1; j <= 1 && !b; j++) for (int i = -1; i <= 1 && !b; i++) {
                    int yy = y + j, xx = x + i;
                    if (yy >= 0 && yy < mh && xx >= 0 && xx < mw && soft[yy][xx]) b = true;
                }
                big[y][x] = b;
            }
            BufferedImage out = new BufferedImage(w, h, BufferedImage.TYPE_INT_RGB);
            out.getGraphics().drawImage(img, 0, 0, null);
            int cr = Math.max(5, (int) Math.round(5 * k));
            float[][][] res = new float[3][mh][mw];
            int[][] src = new int[mh][mw];
            for (int y = 0; y < mh; y++) for (int x = 0; x < mw; x++) src[y][x] = out.getRGB(x0 + x, y0 + y);
            for (int ch = 0; ch < 3; ch++) {
                int sh = 16 - 8 * ch;
                for (int y = 0; y < mh; y++) for (int x = 0; x < mw; x++) {
                    float v = (src[y][x] >> sh) & 255, al = a[y][x];
                    float r = al > 0 ? (v - 255f * al) / (1f - al) : v;
                    if (big[y][x]) {
                        // Yakındaki logo dışı piksellerin aralığına sıkıştır (saydamlık az farklıysa koyu/açık leke kalmasın)
                        float lo = 1e9f, hi = -1e9f;
                        for (int j = -cr; j <= cr; j++) { int yy = y + j; if (yy < 0 || yy >= mh) continue;
                            for (int i = -cr; i <= cr; i++) { int xx = x + i; if (xx < 0 || xx >= mw || big[yy][xx]) continue;
                                float n = (src[yy][xx] >> sh) & 255; if (n < lo) lo = n; if (n > hi) hi = n; } }
                        if (lo < 1e8f) r = Math.max(lo - 6, Math.min(hi + 6, r));
                    }
                    res[ch][y][x] = Math.max(0, Math.min(255, r));
                }
            }
            // Logo ve bir piksel çevresinde 3x3 ortanca (JPEG kalıntısını yumuşatır)
            float[] win = new float[9];
            for (int y = 0; y < mh; y++) for (int x = 0; x < mw; x++) {
                int rgb = 0;
                boolean near = false;
                for (int j = -1; j <= 1 && !near; j++) for (int i = -1; i <= 1 && !near; i++) {
                    int yy = y + j, xx = x + i;
                    if (yy >= 0 && yy < mh && xx >= 0 && xx < mw && big[yy][xx]) near = true;
                }
                for (int ch = 0; ch < 3; ch++) {
                    float v = res[ch][y][x];
                    if (near) {
                        int n = 0;
                        for (int j = -1; j <= 1; j++) for (int i = -1; i <= 1; i++) {
                            int yy = Math.max(0, Math.min(mh - 1, y + j)), xx = Math.max(0, Math.min(mw - 1, x + i));
                            win[n++] = res[ch][yy][xx];
                        }
                        Arrays.sort(win); v = win[4];
                    }
                    rgb = (rgb << 8) | Math.round(v);
                }
                if (near) out.setRGB(x0 + x, y0 + y, rgb);
            }
            return out;
        } catch (Throwable t) {
            return img;
        }
    }
